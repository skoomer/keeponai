# 7 .3 .2 . Оптимизация гиперпараметров
# При создании модели глубокого обучения приходится принимать множество решений, кажущихся произвольными: сколько слоев включить в стек? сколько параметров или фильтров должно быть в каждом слое? использовать ли функцию активации relu или какую-то другую? использовать ли BatchNormalization после данного слоя? какой шаг прореживания выбрать? И так далее. Все эти архитек- турные параметры называют гиперпараметрами, чтобы отличать их от параметров модели, которые обучаются посредством обратного распространения ошибки.



# Однако перебор разных пара- метров не должен быть вашей основной работой — это дело лучше доверить машине.
# Другими словами, вам нужно автоматически, систематически и принципиально ис- следовать пространство возможных решений. Вам нужно эмпирически исследовать пространство архитектур и найти ту из них, которая сможет обеспечить лучшее ка- чество. Именно эту задачу решает автоматическая оптимизация гиперпараметров: это огромная и очень важная область исследований.


# Вот как выглядит типичный процесс оптимизации гиперпараметров:
# 1. Выбрать набор гиперпараметров (автоматически).
# 2. Создать соответствующую модель.
# 3. Обучить ее на обучающих данных и оценить качество на проверочных данных.
# 4. Выбрать следующий набор гиперпараметров (автоматически).
# 5. Повторить.
# 6. Получить окончательную оценку качества на контрольных данных.



# Проблемы сложны, а область еще молода, поэтому в настоящее время в нашем распоряжении имеется весьма ограниченный набор инструментов для оптимиза- ции моделей. Часто случайный поиск (многократный выбор случайных значений гиперпараметров) оказывается лучшим решением, несмотря на то что он самый простой. Однако я обнаружил один инструмент, который достоверно лучше слу- чайного поиска, — Hyperopt (https://github.com/hyperopt/hyperopt), библиотеку на Python для оптимизации гиперпараметров: внутренне она использует деревья оценок Парзена для предсказания наборов гиперпараметров, которые с высокой вероятностью дадут положительный результат. Еще одна библиотека, с названием Hyperas (https://github.com/maxpumperla/hyperas), интегрирует Hyperopt для ис- пользования с моделями Keras. Обязательно обратите на нее внимание.



# ПРИМЕЧАНИЕ
# При использовании автоматического оптимизатора гиперпараметров важно пом- нить об одной важной проблеме — переобучении на проверочном наборе. Посколь- ку настройка гиперпараметров выполняется по результатам оценки на проверочных данных, фактически происходит их обучение на проверочном наборе, и, как след- ствие, быстро наступает эффект их переобучения. Всегда помните об этом.



# В целом оптимизация гиперпараметров — мощный метод, абсолютно необходимый в любых задачах для создания моделей, способных победить в состязаниях по ма- шинному обучению. Когда-то люди вручную выбирали признаки, которые затем передавались в поверхностные модели машинного обучения. Этот подход был очень неоптимален. Теперь глубокое обучение автоматизирует конструирование



# 7 .3 .3 . Ансамблирование моделей
# Еще один метод улучшения результатов в решении задач — ансамблирование моделей. Суть метода ансамблирования заключается в объединении прогнозов, полученных набором разных моделей, для получения лучшего прогноза. Если рассмотреть результаты соревнований по машинному обучению, например, на сайте Kaggle, можно увидеть, что победители используют очень большие ан- самбли моделей, которые неизменно побеждают любые одиночные модели, даже самые лучшие.


# Возьмем в качестве примера задачу классификации. Самый простой способ объ- единить прогнозы из множества классификаторов (ансамблировать классифика- торы) — получить среднее их прогнозов на этапе вывода:
    
preds_a = model_a.predict(x_val)
preds_b = model_b.predict(x_val) # Применение четырех разных моделей
preds_c = model_c.predict(x_val)
preds_d = model_d.predict(x_val)
 
final_preds = 0.25 * (preds_a + preds_b + preds_c + preds_d)

# Этот новый массив прогнозов должен получиться более точным, чем любой из начальных



# Более эффективный способ ансамблирования классификаторов — вычисление взвешенного среднего с определением весов по проверочным данным, когда луч- ший классификатор получает больший вес, а худший — меньший. Для поиска оптимальных весов в ансамбле можно использовать алгоритм случайного поиска или простой оптимизации, такой как Nelder-Mead:
    
    
preds_a = model_a.predict(x_val)
preds_b = model_b.predict(x_val)
preds_c = model_c.predict(x_val)
preds_d = model_d.predict(x_val)

# Эти веса (0.5, 0.25, 0.1, 0.15), как предполагается, получены эмпирическим путем
final_preds = 0.5 * preds_a + 0.25 * preds_b + 0.1 * preds_c + 0.15 * preds_d



