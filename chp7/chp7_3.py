# 7 .3 .1 . Шаблоны улучшенных архитектур
# В предыдущем разделе мы рассмотрели один из важнейших шаблонов проектиро- вания: остаточные связи. Однако есть еще два шаблона, которые вы должны знать: нормализация и раздельные свертки по глубине (depthwise separable convolution). Эти шаблоны особенно хорошо подходят для создания высококачественных глу- боких сверточных нейронных сетей, но их нередко можно встретить во многих других типах архитектур.


# Пакетная нормализация
# Нормализация — это широкая категория методов, стремящихся сделать сходство разных образцов более заметным для модели машинного обучения, что помогает модели выделять и обобщать новые данные.


normalized_data = (data - np.mean(data, axis=...)) / np.std(data, axis=...)


# В предыдущих примерах нормализация выполнялась перед передачей данных в мо- дели. Однако нормализация должна проводиться после каждого преобразования, выполняемого сетью: даже если данные на входе в сеть Dense или Conv2D имеют среднее значение 0 и единичную дисперсию, нет оснований полагать, что то же самое можно будет сказать в отношении данных на выходе.



# Обычно слой BatchNormalization используется после сверточного или полно- связного слоя:
    
conv_model.add(layers.Conv2D(32, 3, activation='relu'))
conv_model.add(layers.BatchNormalization())  # После слоя Conv 
dense_model.add(layers.Dense(32, activation='relu'))
dense_model.add(layers.BatchNormalization())  # После слоя dense 


# Слой BatchNormalization принимает аргумент axis, определяющий ось призна- ков для нормализации. По умолчанию этот аргумент принимает значение –1,



# Эти преимущества особенно важны для обучения небольших моделей с нуля на ограниченном наборе данных. Например, вот как можно построить легковесную нейронную сеть со сверткой по глубине для решения задачи классификации изо- бражений (с применением классификатора softmax) при небольшом объеме обу- чающих данных:


from keras.models import Sequential, Model
from keras import layers

height = 64 
width = 64
channels = 3

num_classes = 10

model = Sequential()

model.add(layers.SeparableConv2D(32, 3,
activation='relu',
input_shape=(height, width, channels,)))


model.add(layers.SeparableConv2D(64, 3, activation='relu'))
model.add(layers.MaxPooling2D(2))

model.add(layers.SeparableConv2D(64, 3, activation='relu'))
model.add(layers.SeparableConv2D(128, 3, activation='relu'))
model.add(layers.MaxPooling2D(2))

model.add(layers.SeparableConv2D(64, 3, activation='relu'))
model.add(layers.SeparableConv2D(128, 3, activation='relu')) 

model.add(layers.GlobalAveragePooling2D())
model.add(layers.Dense(32, activation='relu')) 

model.add(layers.Dense(num_classes, activation='softmax'))
model.compile(optimizer='rmsprop', loss='categorical_crossentropy')


# В отношении крупных моделей раздельные свертки по глубине составляют основу архитектуры Xception высококачественных сверточных нейронных сетей, входя- щей в состав Keras.


