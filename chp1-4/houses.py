# Листинг 3.28. Сохранение оценки проверки перед каждым прогоном

num_epochs = 500

all_mae_histories = []


for i in range(k):
    print('processing fold #', i)
    val_data = train_data[i * num_val_samples: (i + 1) * num_val_samples] #Подготовка проверочных данных: данных из блока с номером k 
    val_targets = train_targets[i * num_val_samples: (i + 1) * num_val_samples]
    
    partial_train_data = np.concatenate( [train_data[:i * num_val_samples], train_data[(i + 1) * num_val_samples:]], axis=0) #Подготовка обучающих данных: данных из остальных блоков
    partial_train_targets = np.concatenate( [train_targets[:i * num_val_samples], train_targets[(i + 1) * num_val_samples:]], axis=0)
    
    model = build_model() #Конструирование модели Keras (уже скомпилированной)
    
    history = model.fit(partial_train_data, partial_train_targets, validation_data=(val_data, val_targets), epochs=num_epochs, batch_size=1, verbose=0) # Обучение модели (в режиме без вывода сообщений, verbose = 0)
    mae_history = history.history['val_mae']
    all_mae_histories.append(mae_history)



# Да, вы правы, это относится к остальным трем блокам в контексте k-fold кросс-валидации. В этом цикле кода каждый блок (фолд) используется как проверочные данные (validation set), а остальные три блока объединяются в один блок, который служит обучающими данными (training set). Таким образом, "остальные блоки" означают блоки, которые не являются текущим блоком, используемым в качестве проверочных данных.

# В контексте вашего кода, цикл выполняется для каждого из четырех блоков, и в каждой итерации текущий блок служит проверочными данными (val_data, val_targets), а остальные три блока объединяются в обучающие данные (partial_train_data, partial_train_targets). Таким образом, при каждой итерации цикла модель обучается четыре раза (на четырех разных наборах данных), и каждый блок используется в качестве проверочных данных один раз.
