# 3.6.3. Конструирование сети
# Из-за небольшого количества образцов мы будем использовать очень маленькую сеть с двумя четырехмерными промежуточными слоями. Вообще говоря, чем меньше обучающих данных, тем скорее наступит переобучение, а использование маленькой сети — один из способов борьбы с ним.


# Листинг 3.26. Определение модели

from keras import models
from keras import layers



def build_model():
    model = models.Sequential() #Поскольку нам потребуется несколько экземпляров одной и той же модели, мы определили функцию для ее создания
    model.add(layers.Dense(64, activation='relu',input_shape=(train_data.shape[1],)))
    model.add(layers.Dense(64, activation='relu'))
    model.add(layers.Dense(1))
    
    model.compile(optimizer='rmsprop', loss='mse', metrics=['mae'])
    return model


# Сеть заканчивается одномерным слоем, не имеющим функции активации (это линейный слой). Это типичная конфигурация для скалярной регрессии (целью которой является предсказание одного значения на непрерывной числовой прямой). Применение функции активации могло бы ограничить диапазон выходных значений: например, если в последнем слое применить функцию активации sigmoid, сеть обучилась бы предсказывать только значения из диапазона между 0 и 1. В данном случае, с линейным последним слоем, сеть способна предсказывать значения из любого диапазона.

# Обратите внимание на то, что сеть компилируется с функцией потерь mse — mean squared error (среднеквадратичная ошибка), вычисляющей квадрат разности между предсказанными и целевыми значениями. Эта функция широко используется в задачах регрессии.

# Мы также включили новый параметр в мониторинг на этапе обучения: mae — mean absolute error (средняя абсолютная ошибка). Это абсолютное значение разности между предсказанными и целевыми значениями. Например, значение MAE, равное 0,5, в этой задаче означает, что в среднем прогнозы отклоняются на 500 долларов США.


# 3.6.4. Оценка решения методом перекрестной проверки по K блокам
# Чтобы оценить качество сети в ходе корректировки ее параметров (таких, как количество эпох обучения), можно разбить исходные данные на обучающий и проверочный наборы, как это делалось в предыдущих примерах. Однако так как у нас и без того небольшой набор данных, проверочный набор получился бы слишком маленьким (скажем, что-нибудь около 100 образцов). Как следствие, оценки при проверке могут сильно меняться в зависимости от того, какие данные попадут в проверочный и обучающий наборы: оценки при проверке могут иметь слишком большой разброс. Это не позволит надежно оценить качество модели.

# Лучшей практикой в таких ситуациях является применение перекрестной проверки по K блокам (K-fold cross-validation), как показано на рис. 3.11. Суть ее заключается в разделении доступных данных на K блоков (обычно K = 4 или 5), создании K идентичных моделей и обучении каждой на K—1 блоках с оценкой по оставшимся блокам. По полученным K оценкам вычисляется среднее значение, которое принимается как оценка модели. В коде такая проверка реализуется достаточно просто.


# Листинг 3.27. Перекрестная проверка по K блокам


import numpy as np

k = 4
num_val_samples = len(train_data) // k

num_epochs = 100

all_scores = []

for i in range(k):
    print('processing fold #', i)
    val_data = train_data[i * num_val_samples: (i + 1) * num_val_samples] #Подготовка проверочных данных: данных из блока с номером k 
    val_targets = train_targets[i * num_val_samples: (i + 1) * num_val_samples]
    
    partial_train_data = np.concatenate( [train_data[:i * num_val_samples], train_data[(i + 1) * num_val_samples:]], axis=0) #Подготовка обучающих данных: данных из остальных блоков
    
    partial_train_targets = np.concatenate( [train_targets[:i * num_val_samples], train_targets[(i + 1) * num_val_samples:]], axis=0)
    
    model = build_model() #Конструирование модели Keras (уже скомпилированной)
    model.fit(partial_train_data, partial_train_targets, epochs=num_epochs, batch_size=1, verbose=0) #Обучение модели (в режиме без вывода сообщений , verbose = 0)
    
    val_mse, val_mae = model.evaluate(val_data, val_targets, verbose=0) #Оценка модели по проверочным данным(val_mse)
    all_scores.append(val_mae)
    
    
    
# val_data = train_data[i * num_val_samples: (i + 1) * num_val_samples]:

# i * num_val_samples: Это определяет начальный индекс среза. Умножение i * num_val_samples позволяет выбрать стартовую позицию данных в train_data для текущего блока (фолда) в k-fold кросс-валидации.

# (i + 1) * num_val_samples: Это определяет конечный индекс среза. Умножение (i + 1) * num_val_samples определяет конечную позицию данных в train_data для текущего блока.

# train_data[i * num_val_samples: (i + 1) * num_val_samples]: Это создает срез (slice) из train_data для текущего блока. Он включает в себя данные, начиная с индекса i * num_val_samples и заканчивая индексом (i + 1) * num_val_samples - 1.

# train_targets[i * num_val_samples: (i + 1) * num_val_samples]: Это создает срез (slice) из train_targets для текущего блока. Он включает в себя целевые значения, начиная с индекса i * num_val_samples и заканчивая индексом (i + 1) * num_val_samples - 1.

# Давайте разберем подробно строку partial_train_data = np.concatenate([train_data[:i * num_val_samples], train_data[(i + 1) * num_val_samples:]], axis=0):

# train_data[:i * num_val_samples]: Эта часть выбирает данные обучения до начала текущего блока (фолда). Оператор среза [:i * num_val_samples] означает выбор данных с самого начала до индекса (i * num_val_samples - 1).

# train_data[(i + 1) * num_val_samples:]: Эта часть выбирает данные обучения после окончания текущего блока (фолда). Оператор среза [(i + 1) * num_val_samples:] означает выбор данных, начиная с индекса ((i + 1) * num_val_samples) и до конца массива.

# np.concatenate([...], axis=0): Это функция NumPy, которая объединяет два массива данных. Здесь она объединяет два среза данных обучения вдоль оси 0 (по вертикали), создавая таким образом один массив данных обучения для текущего блока.

# Итак, partial_train_data представляет собой данные обучения, исключая текущий блок (фолд) в k-fold кросс-валидации. Эта строка позволяет создать обучающий набор данных, который используется для обучения модели, исключая данные для текущего блока валидации.
