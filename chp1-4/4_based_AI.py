# 4 .4 .3 . Добавление прореживания
# Прореживание (dropout) — один из наиболее эффективных и распространенных приемов регуляризации для нейронных сетей, разработанный Джеффом Хинтоном (Geoff Hinton) и его студентами в Университете Торонто. Прореживание, которое применяется к слою, заключается в удалении (присваивании нуля) случайно вы- бираемым признакам на этапе обучения. Представьте, что в процессе обучения не- который уровень для данного образца на входе в нормальной ситуации возвращает вектор [0,2, 0,5, 1,3, 0,8, 1,1]. После применения прореживания некоторые элементы вектора получают нулевое значение: например, [0, 0,5, 1,3, 0, 1,1]. Коэффициент про- реживания — это доля обнуляемых признаков; обычно он выбирается в диапазоне от 0,2 до 0,5. На этапе тестирования прореживание не производится; вместо этого выходные значения уровня уменьшаются на коэффициент, равный коэффициенту прореживания, чтобы компенсировать разницу в активности признаков на этапах тестирования и обучения.





# Рассмотрим матрицу Numpy, содержащую результат слоя, layer_output, с формой (размер_пакета, признаки). На этапе обучения мы обнуляем случайно выбираемые значения в матрице:
    
layer_output *= np.random.randint(0, high=2, size=layer_output.shape) # На этапе обучения обнуляется 50% признаков в выводе

# На этапе тестирования мы уменьшаем результаты на коэффициент прореживания. В данном случае на коэффициент 0,5 (потому что прежде была отброшена половина признаков):
layer_output *= 0.5 #На этапе тестирования

# Обратите внимание на то, что этот процесс можно реализовать полностью на этапе обучения и оставить без изменения результаты, получаемые на этапе тестирования, что часто и делается на практике (рис. 4.8):


layer_output *= np.random.randint(0, high=2, size=layer_output.shape) # На этапе обучения
layer_output /= 0.5 # Обратите внимание: в данном случае происходит увеличение, а не уменьшение значений

# Этот прием может показаться странным и необоснованным. Каким образом он по- может справиться с переобучением? По словам Хинтона, основой для этого приема, кроме всего прочего, стал механизм, используемый банками для предотвращения мошенничества. Вот его слова: «Посещая свой банк, я заметил, что операционисты, обслуживающие меня, часто меняются. Я спросил одного из них, почему так про- исходит. Он сказал, что не знает, но им часто приходится переходить с места на место. Я предположил, что это делается для исключения мошеннического сговора клиента с сотрудником банка. Это навело меня на мысль, что удаление случайно

# выбранного подмножества нейронов из каждого примера может помочь предот- вратить заговор модели с исходными данными и тем самым ослабить эффект переобучения»1. Основная идея заключается в том, что введение шума в выход- ные значения может разбить случайно складывающиеся шаблоны, не имеющие большого значения (Хинтон называет их заговорами), которые модель начинает запоминать в отсутствие шума.

