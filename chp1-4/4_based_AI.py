# 4 .1 . Четыре раздела машинного обучения
# В предыдущих примерах вы познакомились с тремя конкретными типами задач машинного обучения: бинарной классификацией, многоклассовой классификацией и скалярной регрессией. Все три являются примерами контролируемого обучения, когда целью является научиться сопоставлять исходные тренировочные данные с тренировочными целями.

# Контролируемое обучение — это лишь верхушка айсберга. Машинное обучение — это обширная область со сложным делением на разделы. Алгоритмы машинного обучения обычно делятся на четыре основные категории, которые описываются в следующих разделах.


    
# 4 .1 .1 . Контролируемое обучение
# Этот случай, безусловно, является наиболее распространенным. Его суть заклю- чается в том, чтобы научить модель отображать исходные данные в известные целевые значения (иногда их также называют аннотациями) на наборе примеров (часто аннотированных людьми). Все четыре примера, которые вы видели выше в этой книге, являются каноническими примерами контролируемого обучения. Вообще говоря, к этой категории относятся почти все современные способы при- менения глубокого обучения, такие как распознавание образов, распознавание речи, классификация изображений и перевод с одного языка на другой.
# Основную долю задач контролируемого обучения составляют классификация и регрессия, но есть и более экзотические варианты, включая следующие (с при- мерами):
# Генерация последовательностей — по заданной картинке предсказать заголовок, который ее описывает. Иногда генерацию последовательностей можно сформу- лировать как серию задач классификации (таких, как повторяющее предсказа- ние следующего слова в последовательности).
# Прогнозирование дерева синтаксиса — по имеющемуся предложению требуется спрогнозировать его разложение в дерево синтаксиса.
# Распознавание объектов — на имеющейся картинке требуется нарисовать рамки вокруг определенных объектов. Эту задачу тоже можно выразить как задачу классификации (по множеству возможных рамок классифицировать содержи- мое каждой) или как сочетание классификации и регрессии, когда координаты рамок предсказываются посредством векторной регрессии.
# Сегментирование изображений — по имеющейся картинке построить пиксель- ную маску для конкретного объекта.


# 4 .1 .2 . Неконтролируемое обучение
# Этот раздел машинного обучения заключается в поиске интересных преобра- зований входных данных без помощи каких-либо целевых значений для нужд визуализации, сжатия или очистки данных от шумов или для лучшего понимания взаимосвязей в данных. Неконтролируемое обучение — это основа анализа данных, оно часто оказывается необходимым шагом на пути изучения набора данных перед применением методов контролируемого обучения. Хорошо известными примерами неконтролируемого обучения являются понижение размерности и кластеризация.

# 4 .1 .3 . Самоконтролируемое обучение
# Это разновидность контролируемого обучения, которая имеет существенные отли- чия, а потому может быть выделена в отдельную категорию. Самоконтролируемое обучение контролируется без использования меток, расставленных человеком, — самоконтролируемое обучение можно считать контролируемым обучением без участия людей. Здесь также имеются метки (иначе это обучение не было бы контро- лируемым), однако они генерируются из исходных данных, обычно с применением эвристических алгоритмов


# 4 .1 .4 . Обучение с подкреплением
# Этот вид машинного обучения долгое время обходили вниманием, пока в Google DeepMind не добились успеха, обучив компьютер играть в игры Atari (а позднее в Go на высочайшем уровне). В обучении с подкреплением агент получает инфор- мацию о своем окружении и учится выбирать действия, максимизирующие неко- торую выгоду. Например, с помощью обучения с подкреплением можно получить нейронную сеть, которая «смотрит» на экран видеоигры и руководит действиями игрока, максимизируя количество очков.

# ГЛОССАРИЙ КЛАССИФИКАЦИИ И РЕГРЕССИИ
# Классификация и регрессия вводят множество специальных терминов . Некоторые из них уже встречались нам в предыдущих примерах, и еще больше их встретится в следу- ющих главах . Они имеют точные определения, характерные для машинного обучения, и вы должны знать их .



# • Образец (sample), или вход (input), — один экземпляр данных, поступающий в модель .

# • Прогноз, предсказание (prediction), или выход (output), — результат работы мо- дели .

# • Цель (target) — истина . То, что в идеале должна спрогнозировать модель по данным из внешнего источника .

# • Ошибка прогноза (prediction error), или значение уровня потерь (loss value), — мера расстояния между прогнозом модели и целью .

# • Классы (classes) — набор меток в задаче классификации, доступных для выбора . Например, в задаче классификации изображений с кошками и собаками доступны два класса: «собака» и «кошка» .

# • Метка (label) — конкретный экземпляр класса в задаче классификации . Напри- мер, если изображение No 1234 аннотировано как принадлежащее классу «со- бака», тогда «собака» является меткой для изображения No 1234 .
# • Эталоны (ground-truth), или аннотации (annotations), — все цели для набора данных, обычно собранные людьми .
# • Бинарная классификация (binary classification) — задача классификации, которая должна разделить входные данные на две взаимоисключающие категории .
# • Многоклассовая классификация (multiclass classification) — задача классифика- ции, которая должна разделить входные данные на более чем две категории . Примером может служить классификация рукописных цифр .
# • Многозначная, или нечеткая, классификация (multilabel classification) — зада- ча классификации, в которой каждому входному образцу можно присвоить не- сколько меток . Например, на картинке могут быть изображены кошка и собака вместе, и поэтому такая картинка должна аннотироваться двумя метками: «кош- ка» и «собака» . Количество меток, присваиваемых изображениям, обычно может меняться .

# • Скалярная регрессия (scalar regression) — задача, в которой цель является ска- лярным числом, лежащим на непрерывной числовой прямой . Хорошим примером может служить прогнозирование цен на жилье: разные цены из непрерывного диапазона .
# • Векторная регрессия (vector regression) — задача, в которой цель является на- бором чисел, лежащих на непрерывной числовой прямой . Например, регрессия по нескольким значениям (таким, как координаты прямоугольника, ограничива- ющего изображение) является векторной регрессией .
# • Пакет или мини-пакет (batch или mini-batch) — небольшой набор образцов (обычно от 8 до 128), обрабатываемых моделью одновременно . Число образцов часто является степенью двойки для более эффективного использования памяти GPU . В процессе обучения один мини-пакет используется в градиентном спуске для вычисления одного изменения весов модели .


