# 4 .4 .2 . Добавление регуляризации весов
# Возможно вы знакомы с принципом бритвы Оккама: если какому-то явлению можно дать два объяснения, правильным, скорее всего, будет более простое — имеющее меньшее количество допущений. Эта идея применима также к моделям, полученным с помощью нейронных сетей: для одних и тех же наборов тренировоч- ных данных и архитектуры сети существует множество наборов весовых значений (моделей), объясняющих данные. Более простые модели менее склонны к переобу- чению, чем сложные.

# Простая модель в данном контексте — это модель, в которой распределение значений параметров имеет меньшую энтропию (или модель с меньшим числом параметров, как было показано в предыдущем разделе). То есть типичный способ смягчения про- блемы переобучения заключается в уменьшении сложности сети путем ограничения значений ее весовых коэффициентов, что делает их распределение более равно- мерным. Этот прием называется регуляризацией весов, он реализуется добавлением в функцию потерь сети штрафа за увеличение весов и имеет две разновидности:
# L1-регуляризация (L1 regularization) — добавляемый штраф прямо пропорцио- нален абсолютным значениям весовых коэффициентов (L1-норма весов).
# L2-регуляризация (L2 regularization) — добавляемый штраф пропорционален квадратам значений весовых коэффициентов (L2-норма весов). В контексте нейронных сетей L2-регуляризация также называется сокращением весов (weight decay). Это два разных названия одного и того же явления: сокращение весов с математической точки зрения суть то же самое, что L2-регуляризация.

# В Keras регуляризация весов осуществляется путем передачи в слои именованных аргументов с экземплярами регуляризаторов весов. Рассмотрим пример добавления L2-регуляризации в сеть классификации отзывов о фильмах (листинг 4.6




# Листинг 4.6. Добавление L2-регуляризации весов в модель
