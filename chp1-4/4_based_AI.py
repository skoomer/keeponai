# 4 .4 . Переобучение и недообучение
# Во всех трех примерах из предыдущей главы: определение эмоциональной окраски отзыва, классификация по темам и регрессия цен на дома — качество модели на проверочных данных всегда достигало максимума после небольшого количества эпох и затем начинало падать — модель быстро достигала эффекта переобучения. Переобучение наблюдается во всех задачах машинного обучения. Умение справ- ляться с этим эффектом играет важную роль в машинном обучении.
# Основной проблемой машинного обучения является противоречие между оптими- зацией и общностью. Под оптимизацией понимается процесс настройки модели для получения максимального качества на тренировочных данных (обучение в машин- ном обучении), а под общностью — качество обученной модели на данных, которые она прежде не видела. Цель игры — добиться высокого уровня общности, но вы не можете управлять общностью, вы можете только настраивать модель, опираясь на тренировочные данные.

# Лучший способ предотвратить изучение моделью специфических или нерелевант- ных шаблонов, имеющих место в тренировочных данных, — увеличить объем тре- нировочных данных. Модель, обученная на большем объеме данных, будет иметь бо льшуюобщность.Еслиэтоневозможно,следующимлучшимспособомявляется регулирование качества информации или добавление ограничений на информацию, которую модели будет позволено сохранить. Если сеть может позволить себе со- хранить только небольшое количество шаблонов, процесс оптимизации заставит ее сосредоточиться на наиболее существенных из них, что увеличит шансы на до- стижение более высокого уровня общности.
