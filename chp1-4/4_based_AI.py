model = models.Sequential()
model.add(layers.Dense(16, kernel_regularizer=regularizers.l2(0.003),
activation='relu', input_shape=(10000,)))
model.add(layers.Dense(16, kernel_regularizer=regularizers.l2(0.002),
activation='relu'))
model.add(layers.Dense(1, activation='sigmoid'))

# l2(0.001) означает, что каждый коэффициент в матрице весов слоя будет добавлять 0.001 * weight_coefficient_value в общее значение потерь сети. Обратите внима- ние: так как штраф добавляется только на этапе обучения, величина потерь сети на этапе обучения будет намного выше, чем на этапе контроля.
