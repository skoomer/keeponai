# 4 .2 .2 . Что важно помнить
# Выбирая протокол оценки, всегда помните:

# о репрезентативности данных — наборы тренировочных и контрольных данных должны быть репрезентативными для всего объема имеющихся данных. На- пример, если вы пытаетесь классифицировать изображения рукописных цифр и имеете массив, в котором образцы упорядочены по классам, использование первых 80 % образцов для обучения и остальных 20 % для контроля приведет к тому, что тренировочный набор будет содержать классы 0–7, а контрольный набор — только классы 8–9. Эта ошибка может показаться смешной, однако ее совершают слишком часто. По этой причине всегда желательно перемешивать данные перед делением на тренировочный и контрольный наборы;

# о направлении оси времени — пытаясь предсказать будущее по прошлому (на- пример, погоду на завтра, движение товаров и т. д.), вы не должны производить перемешивание данных перед делением, потому что это создаст временную утечку: ваша модель фактически будет обучаться по данным в будущем. В таких ситуациях всегда нужно следить за тем, чтобы контрольные данные следовали непосредственно за тренировочными данными;
# об избыточности данных — если некоторые образцы присутствуют в данных в нескольких экземплярах (частое явление в реальном мире), перемешивание и деление данных на тренировочный и проверочный наборы приведет к появ- лению избыточности между тренировочным и проверочным наборами. По сути, вы будете проводить тестирование на части тренировочных данных, что является худшим из зол! Убедитесь в том, что тренировочный и проверочный наборы не пересекаются.

# 4 .3 . Обработка данных, конструирование признаков и обучение признаков
# Помимо оценки модели, мы должны затронуть еще один важный вопрос, пре- жде чем погрузиться в разработку моделей: как подготовить исходные данные и цели перед передачей их в нейронную сеть? Многие приемы обработки данных и конструирования признаков в значительной мере зависят от предметной об- ласти (например, подготовка текстовых данных или образов); мы рассмотрим их в следующих разделах на конкретных примерах. А пока познакомимся с основами, общими для всех предметных областей.

# 4 .3 .1 . Предварительная обработка данных
# для нейронных сетей
# Цель предварительной обработки данных — сделать исходные данные пригодными для передачи в нейронную сеть. Сюда входят векторизация, нормализация, обра- ботка недостающих значений и извлечение признаков.


# Векторизация
# Все входы и цели в нейронной сети должны быть тензорами чисел с плавающей точкой (или, в особых случаях, тензорами целых чисел). Какие бы данные вам ни требовалось обработать — звук, изображение, текст, — их сначала нужно преобра- зовать в тензоры. Этот шаг называется векторизацией данных. Например, в двух предыдущих примерах классификации текстовых данных мы начали с того, что преобразовали текст в списки целых чисел (представляющие собой последователь- ности слов) и применили прямое кодирование для превращения списков в тензоры данных типа float32. В примерах классификации изображений цифр и предска- зания цен на дома исходные данные уже имеют векторизованную форму, поэтому мы пропустили этот шаг.



# Нормализация значений
# В примере классификации цифр исходные черно-белые изображения цифр были представлены массивами целых чисел в диапазоне 0–255. Прежде чем передать эти данные в сеть, нам понадобилось привести числа к типу float32 и разделить каждое на 255, в результате чего у нас получились массивы чисел с плавающей точкой в диапазоне 0–1. Аналогично, в примере с предсказанием цен на дома у нас имелись наборы признаков со значениями в разных диапазонах: некоторые при- знаки были выражены значениями с плавающей точкой, другие — целочисленными значениями. Перед передачей данных в сеть нам понадобилось нормализовать каждый признак в отдельности, чтобы все они имели среднее значение, равное 0, и стандартное отклонение, равное 1.

# Чтобы упростить обучение сети, данные должны обладать следующими характеристиками:
# принимать небольшие значения — как правило, значения должны находиться в диапазоне 0–1;


# быть однородными — то есть все признаки должны принимать значения из при-
# мерно одного и того же диапазона.

# Кроме того, может оказаться полезной следующая практика нормализации, хотя она не всегда необходима (например, мы не использовали нормализацию в примере классификации цифр):

# нормализация каждого признака независимо, чтобы его среднее значение было равно 0;
# нормализация каждого признака независимо, чтобы его стандартное отклонение было равно 1.

# Это легко реализуется с применением массивов Numpy:



x -= x.mean(axis=0)#Предполагается, что x — это двумерная матрица данных с формой (образцы, свойства)
x /= x.std(axis=0)


# Обработка недостающих значений
# Иногда в исходных данных могут отсутствовать некоторые значения. Так, в при- мере с предсказанием цен на дома первым признаком (столбец с индексом 0 в дан- ных) был уровень преступности на душу населения. Как быть, если этот признак определен не во всех образцах? Если оставить все как есть, у нас будет недоставать значений в тренировочных или в контрольных данных.
# Вообще в случае с нейронными сетями вполне безопасно заменить недостающие входные значения нулями, при условии, что 0 не является осмысленным значени- ем. Обрабатывая данные, сеть поймет, что 0 означает отсутствие данных, и будет игнорировать это значение.

