# Вот как можно реализовать модуль, изображенный на рис. 7.8, с помощью функ- ционального API. Этот пример предполагает наличие четырехмерного входного тензора x:


# branch_a Все ветви имеют одинаковый шаг свертки (2). Это необходимо для получения на выходе всех ветвей тензоров одного размера, чтобы потом их можно было объединить
# branch_b В этой ветви шагание происходит в слое пространственной свертки
# branch_c В этой ветви шагание происходит в слое извлечения среднего по соседям


# output Объединение результатов, возвращаемых ветвями для получения результата работы модуля
from keras import layers 


branch_a = layers.Conv2D(128, 1, activation='relu', strides=2)(x)
branch_b = layers.Conv2D(128, 1, activation='relu')(x)
branch_b = layers.Conv2D(128, 3, activation='relu', strides=2)(branch_b)

branch_c = layers.AveragePooling2D(3, strides=2)(x)
branch_c = layers.Conv2D(128, 3, activation='relu')(branch_c)

branch_d = layers.Conv2D(128, 1, activation='relu')(x)
branch_d = layers.Conv2D(128, 3, activation='relu')(branch_d)
branch_d = layers.Conv2D(128, 3, activation='relu', strides=2)(branch_d)

output = layers.concatenate(
[branch_a, branch_b, branch_c, branch_d], axis=-1)

