
# 7 .1 .4 . Ориентированные ациклические графы уровней

# Фреймворк Keras позволяет создавать нейронные сети, организован- ные как произвольные ориентированные ациклические графы слоев. Уточнение ациклические очень важно: такие графы не имеют замкнутых маршрутов. Тензор x не может служить входом в один из слоев, генерирующих x. Единственными до- пустимыми циклами обработки (то есть рекуррентными связями) являются циклы внутри рекуррентных слоев


